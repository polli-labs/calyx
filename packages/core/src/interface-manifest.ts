export interface InterfaceManifest {
  schema_version: typeof INTERFACE_MANIFEST_SCHEMA_VERSION;
  generated_from: "hand-authored-wave-4-slice";
  domains: readonly InterfaceDomainClassification[];
  records: readonly InterfaceManifestRecord[];
  external_services: readonly InterfaceExternalServiceDescriptor[];
}

function capabilityBinding(capabilityId: string): Pick<InterfaceManifestRecord, "capability"> | Record<string, never> {
  const registered = findInterfaceCapabilityContract(capabilityId);
  return registered ? { capability: registered.id } : {};
}

