function summarizeConditionalBoolean(values: readonly boolean[]): InterfaceConditionalBoolean {
  return values.every((value) => value === values[0]) ? values[0]! : "mixed";
}

function summarizeHttpEffectLevel(values: readonly HttpOperationEffectLevel[]): InterfaceEffectLevel {
  const unique = new Set(values);
  if (unique.size === 1) return values[0]!;
  if (unique.has("write_without_dry_run")) return "write_without_dry_run";
  if (unique.has("write_on_apply")) return "write_on_apply";
  const reads = unique.has("read") || unique.has("read_write");
  const writes = unique.has("write") || unique.has("read_write");
  if (reads && writes) return "read_write";
  if (writes) return "write";
  if (reads) return "read";
  return "none";
}

function declaredHttpEffects(
  descriptor: HttpOperationDescriptor,
  receiptRequired: InterfaceConditionalBoolean,
): InterfaceEffectsBlock {
  const effects = descriptor.effects.kind === "uniform"
    ? [descriptor.effects.effects]
    : descriptor.effects.branches.map((branch) => branch.effects);
  return {
    local_files: summarizeHttpEffectLevel(effects.map((effect) => effect.local_files)),
    local_state: summarizeHttpEffectLevel(effects.map((effect) => effect.local_state)),
    remote_tracker: summarizeHttpEffectLevel(effects.map((effect) => effect.remote_tracker)),
    remote_provider: summarizeHttpEffectLevel(effects.map((effect) => effect.remote_provider)),
    process_launch: effects.some((effect) => effect.process_launch),
    creates_worktree: effects.some((effect) => effect.creates_worktree),
    dispatches_run: effects.some((effect) => effect.dispatches_run),
    dry_run_default: effects.every((effect) => effect.dry_run_default),
    receipt_required: receiptRequired,
    ...(descriptor.effects.kind === "by_success"
      ? { notes: "Success branches carry distinct effects; inspect operation_effects for the exact branch contract." }
      : descriptor.effects.effects.notes ? { notes: descriptor.effects.effects.notes } : {}),
  };
}

